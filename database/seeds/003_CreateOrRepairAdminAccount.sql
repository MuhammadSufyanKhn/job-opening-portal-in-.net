-- ============================================================================
-- HireSphere / Talent Connect Production Database Script
-- Script ID:   003_CreateOrRepairAdminAccount.sql
-- Description: Idempotently creates or repairs the Platform Administrator account
--              and ensures SuperAdmin & Admin roles exist with valid PBKDF2 hashes.
-- Target DB:   Microsoft SQL Server 2019+ (SSMS)
-- Safety:      Wrapped in TRANSACTION with TRY...CATCH. Non-destructive.
-- ============================================================================

SET NOCOUNT ON;
BEGIN TRANSACTION;

BEGIN TRY
    PRINT N'============================================================================';
    PRINT N'[STEP 1] Ensuring Platform Roles Exist (SuperAdmin and Admin)';
    PRINT N'============================================================================';

    -- Ensure 'Candidate' role exists
    IF NOT EXISTS (SELECT 1 FROM dbo.Roles WHERE NormalizedName = N'CANDIDATE')
    BEGIN
        INSERT INTO dbo.Roles (Id, Name, NormalizedName, Description)
        VALUES (NEWID(), N'Candidate', N'CANDIDATE', N'Candidate job seeker');
        PRINT N'[INFO] Created role: Candidate';
    END;

    -- Ensure 'CompanyMember' role exists
    IF NOT EXISTS (SELECT 1 FROM dbo.Roles WHERE NormalizedName = N'COMPANYMEMBER')
    BEGIN
        INSERT INTO dbo.Roles (Id, Name, NormalizedName, Description)
        VALUES (NEWID(), N'CompanyMember', N'COMPANYMEMBER', N'Company employer team member');
        PRINT N'[INFO] Created role: CompanyMember';
    END;

    -- Ensure 'SuperAdmin' role exists
    IF NOT EXISTS (SELECT 1 FROM dbo.Roles WHERE NormalizedName = N'SUPERADMIN')
    BEGIN
        INSERT INTO dbo.Roles (Id, Name, NormalizedName, Description)
        VALUES (NEWID(), N'SuperAdmin', N'SUPERADMIN', N'Platform Super Administrator with system-wide governance');
        PRINT N'[INFO] Created role: SuperAdmin';
    END;

    -- Ensure 'Admin' role exists as well (supporting both role identifiers)
    IF NOT EXISTS (SELECT 1 FROM dbo.Roles WHERE NormalizedName = N'ADMIN')
    BEGIN
        INSERT INTO dbo.Roles (Id, Name, NormalizedName, Description)
        VALUES (NEWID(), N'Admin', N'ADMIN', N'Platform Administrator');
        PRINT N'[INFO] Created role: Admin';
    END;

    PRINT N'============================================================================';
    PRINT N'[STEP 2] Preparing Administrator Credentials & Verified PBKDF2 Password Hash';
    PRINT N'============================================================================';

    -- Define Admin Email and Name (Change as desired before executing)
    DECLARE @AdminEmail NVARCHAR(256) = N'admin@talentconnect.com';
    DECLARE @AdminNormalized NVARCHAR(256) = UPPER(LTRIM(RTRIM(@AdminEmail)));
    DECLARE @AdminFirstName NVARCHAR(100) = N'Platform';
    DECLARE @AdminLastName NVARCHAR(100) = N'Admin';

    -- Verified PBKDF2 password hash generated by HireSphere's PasswordHasherService
    -- Algorithm: PBKDF2 HMAC-SHA256, 100,000 iterations, 16-byte salt, 32-byte hash
    -- Plaintext Password: AdminSecure2026!
    -- Format: 100000.{SaltBase64}.{HashBase64}
    DECLARE @VerifiedPasswordHash NVARCHAR(MAX) = N'100000.oHPUhsIxo3rTO3fJBU22iA==.dNaNCirI6gB83qTKrajM/q+pazCXB6hpF3zdjQXHshg=';

    DECLARE @AdminUserId UNIQUEIDENTIFIER;
    DECLARE @SuperAdminRoleId UNIQUEIDENTIFIER = (SELECT TOP 1 Id FROM dbo.Roles WHERE NormalizedName = N'SUPERADMIN');
    DECLARE @AdminRoleId UNIQUEIDENTIFIER = (SELECT TOP 1 Id FROM dbo.Roles WHERE NormalizedName = N'ADMIN');

    -- Check if user already exists by NormalizedEmail
    SELECT @AdminUserId = Id FROM dbo.Users WHERE NormalizedEmail = @AdminNormalized;

    IF @AdminUserId IS NULL
    BEGIN
        -- User does not exist: INSERT new Administrator user
        SET @AdminUserId = NEWID();

        INSERT INTO dbo.Users (
            Id,
            Email,
            NormalizedEmail,
            PasswordHash,
            SecurityStamp,
            FirstName,
            LastName,
            PhoneNumber,
            AccountStatus,
            CreatedAtUtc,
            UpdatedAtUtc,
            IsDeleted,
            DeletedAtUtc
        )
        VALUES (
            @AdminUserId,
            @AdminEmail,
            @AdminNormalized,
            @VerifiedPasswordHash,
            REPLACE(NEWID(), '-', ''),
            @AdminFirstName,
            @AdminLastName,
            NULL,
            0, -- AccountStatus: 0 = Active
            SYSDATETIMEOFFSET(),
            SYSDATETIMEOFFSET(),
            0, -- IsDeleted: 0 = False
            NULL
        );

        PRINT N'[SUCCESS] Created new Administrator account: ' + @AdminEmail;
    END
    ELSE
    BEGIN
        -- User already exists: REPAIR password hash, status, and un-delete if soft-deleted
        UPDATE dbo.Users
        SET PasswordHash = @VerifiedPasswordHash,
            SecurityStamp = REPLACE(NEWID(), '-', ''),
            AccountStatus = 0, -- Active
            IsDeleted = 0,
            DeletedAtUtc = NULL,
            UpdatedAtUtc = SYSDATETIMEOFFSET()
        WHERE Id = @AdminUserId;

        PRINT N'[SUCCESS] Repaired existing Administrator account password hash and active status: ' + @AdminEmail;
    END;

    PRINT N'============================================================================';
    PRINT N'[STEP 3] Assigning Administrator Roles in dbo.UserRoles';
    PRINT N'============================================================================';

    -- Assign SuperAdmin role if not already assigned
    IF @SuperAdminRoleId IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM dbo.UserRoles WHERE UserId = @AdminUserId AND RoleId = @SuperAdminRoleId
    )
    BEGIN
        INSERT INTO dbo.UserRoles (UserId, RoleId, AssignedAtUtc)
        VALUES (@AdminUserId, @SuperAdminRoleId, SYSDATETIMEOFFSET());
        PRINT N'[INFO] Assigned role: SuperAdmin to ' + @AdminEmail;
    END;

    -- Also assign Admin role if not already assigned
    IF @AdminRoleId IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM dbo.UserRoles WHERE UserId = @AdminUserId AND RoleId = @AdminRoleId
    )
    BEGIN
        INSERT INTO dbo.UserRoles (UserId, RoleId, AssignedAtUtc)
        VALUES (@AdminUserId, @AdminRoleId, SYSDATETIMEOFFSET());
        PRINT N'[INFO] Assigned role: Admin to ' + @AdminEmail;
    END;

    COMMIT TRANSACTION;

    PRINT N'============================================================================';
    PRINT N'[COMPLETE] Administrator account is ready for production login:';
    PRINT N'  Email:    ' + @AdminEmail;
    PRINT N'  Password: AdminSecure2026!';
    PRINT N'============================================================================';

END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0
        ROLLBACK TRANSACTION;

    DECLARE @ErrMsg NVARCHAR(4000) = ERROR_MESSAGE();
    DECLARE @ErrSev INT = ERROR_SEVERITY();
    DECLARE @ErrState INT = ERROR_STATE();
    RAISERROR (@ErrMsg, @ErrSev, @ErrState);
END CATCH;
GO
